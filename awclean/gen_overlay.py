#!/usr/bin/env python3
"""
Generate src/AWCleanOverlay.h from awclean/overlay.json.

overlay.json is the single source of truth for AWclean's plain-English layer:
  { "<Airwindows name>": {
        "t": "short title",            # shown as "Name - title"
        "c": "CMP",                    # AWclean category code (see CATEGORIES)
        "note": "what it is, in Chris's words where possible",
        "p": [ { "l": "label",         # replaces the abstract parameter name
                 "f": "formula of x",  # optional: real-unit readout, x is 0..1, sr is sample rate
                 "u": "unit", "d": 1,  # optional unit and decimals
                 "lo": "..", "hi": "..",  # optional words for each end of the knob
                 "s": ["A", "B"],      # optional names for stepped values
                 "note": ".." }, ... ] } }

Run:  python3 awclean/gen_overlay.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "overlay.json")
DST = os.path.join(HERE, "..", "src", "AWCleanOverlay.h")

CATEGORIES = {
    "CMP": "Compress & Gate",
    "LIM": "Clip & Limit",
    "SAT": "Saturate & Color",
    "TAP": "Tape",
    "CON": "Console & Summing",
    "EQ": "EQ & Tone",
    "FLT": "Filters",
    "VRB": "Reverb",
    "DLY": "Delay & Doubling",
    "MOD": "Mod & Pitch",
    "DST": "Distort & Amp",
    "STR": "Stereo & Space",
    "LOF": "Lo-fi & Noise",
    "LOW": "Low End",
    "AIR": "Air & De-ess",
    "UTL": "Utility & Meter",
    "DTH": "Dither",
}


def cstr(s):
    if s is None:
        return "nullptr"
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    with open(SRC, encoding="utf-8") as f:
        ov = json.load(f)

    lines = [
        "// GENERATED by awclean/gen_overlay.py from awclean/overlay.json. Do not edit.",
        "#ifndef AWCLEAN_OVERLAY_H",
        "#define AWCLEAN_OVERLAY_H",
        "",
        "#include \"AWCleanOverlayTypes.h\"",
        "",
        "namespace awclean",
        "{",
    ]

    ents = []
    for i, name in enumerate(sorted(ov)):
        e = ov[name]
        if e["c"] not in CATEGORIES:
            sys.exit(f"{name}: unknown category {e['c']}")
        plines = []
        for p in e["p"]:
            steps = "|".join(p["s"]) if "s" in p else None
            plines.append(
                "    {%s, %s, %s, %d, %s, %s, %s, %s}," % (
                    cstr(p["l"]), cstr(p.get("f")), cstr(p.get("u")), p.get("d", -1),
                    cstr(p.get("lo")), cstr(p.get("hi")), cstr(steps), cstr(p.get("note"))))
        if plines:
            lines.append(f"static const Param p_{i}[] = {{")
            lines.extend(plines)
            lines.append("};")
        ents.append("    {%s, %s, %s, %s, %d, %s}," % (
            cstr(name), cstr(e["t"]), cstr(CATEGORIES[e["c"]]), cstr(e.get("note")),
            len(e["p"]), f"p_{i}" if plines else "nullptr"))

    lines.append("")
    lines.append("static const Entry entries[] = {")
    lines.extend(ents)
    lines.append("};")
    lines.append(f"static constexpr int numEntries = {len(ents)};")
    lines.append("} // namespace awclean")
    lines.append("#endif")

    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(ents)} entries to {os.path.normpath(DST)}")


if __name__ == "__main__":
    main()
